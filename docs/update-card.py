class Failed(Exception):
    pass


def update(screen, plat, disk, rel, backup):
    steps = Steps(screen, ["Back up progress and settings", "Download the image",
                           "Check the image", "Write the card", "Put progress back",
                           "Put settings back"])
    try:
        raw = plat.raw(disk["name"])
        # 1. backup
        steps.run(0, "working", backup)
        os.makedirs(backup, exist_ok=True)
        plat.unmount(disk["name"])
        mbr = read_at(raw, 0, SECTOR)
        start, count = partitions(mbr)[2]
        if mbr[510:512] != b"\x55\xaa" or not count:
            raise Failed((0, "the card has no third partition (/data), is it a Tokibot card?"))
        data = read_at(raw, start * SECTOR, count * SECTOR)
        if len(data) != count * SECTOR:
            raise Failed((0, "could not read the /data partition"))
        with open(os.path.join(backup, "data.img"), "wb") as f:
            f.write(data)
        end = (start + count) * SECTOR
        with gzip.open(os.path.join(backup, "card-start.img.gz"), "wb", compresslevel=1) as f:
            with open(raw, "rb", buffering=0) as src:
                done = 0
                while done < end:
                    chunk = src.read(min(CHUNK, end - done))
                    if not chunk:
                        break
                    f.write(chunk)
                    done += len(chunk)
                    steps.note(0, f"whole card  {bar(done, end)}")
        toml = disk.get("toml")
        if toml is not None:
            with open(os.path.join(backup, "tokibot.toml"), "wb") as f:
                f.write(toml)
        steps.ok(0, f"data.img, card-start.img.gz{', tokibot.toml' if toml else ''} in {backup}")

        # 2. download
        steps.run(1, "hungry", rel["url"].rsplit("/", 1)[1])
        img = os.path.join(backup, rel["url"].rsplit("/", 1)[1])
        h = hashlib.sha256()
        with fetch(rel["url"], timeout=60) as r, open(img, "wb") as f:
            total = int(r.headers.get("Content-Length") or rel["size"] or 0)
            got = 0
            while True:
                chunk = r.read(1 << 20)
                if not chunk:
                    break
                f.write(chunk)
                h.update(chunk)
                got += len(chunk)
                steps.note(1, f"{bar(got, total)}  {human(got)}")
        steps.ok(1, f"{rel['tag']}, {human(got)}")

        # 3. checks
        steps.run(2, "flow")
        if rel["sha256"] and h.hexdigest() != rel["sha256"]:
            raise Failed((2, "the download is damaged (checksum differs), nothing written"))
        with lzma.open(img) as f:
            new_mbr = f.read(SECTOR)
        nstart, ncount = partitions(new_mbr)[2]
        if (nstart, ncount) != (start, count):
            raise Failed((2, f"the new image puts /data elsewhere ({nstart}+{ncount}, card has "
                             f"{start}+{count}); nothing written, flash it with Imager instead"))
        steps.ok(2, "checksum and partition layout fit" if rel["sha256"] else "partition layout fits")

        # 4. write
        steps.run(3, "working")
        plat.unmount(disk["name"])
        size_in = os.path.getsize(img)
        fd = os.open(raw, os.O_WRONLY)
        try:
            dec = lzma.LZMADecompressor()
            pending = b""
            with open(img, "rb") as f:
                while True:
                    comp = f.read(1 << 20)
                    if comp:
                        pending += dec.decompress(comp)
                    if len(pending) >= CHUNK or (not comp and pending):
                        n = len(pending) if not comp else len(pending) // CHUNK * CHUNK
                        block = pending[:n]
                        if len(block) % SECTOR:
                            block += b"\0" * (SECTOR - len(block) % SECTOR)
                        view = memoryview(block)
                        while view:
                            view = view[os.write(fd, view):]
                        pending = pending[n:]
                    steps.note(3, bar(f.tell(), size_in))
                    if not comp:
                        break
            os.fsync(fd)
        finally:
            os.close(fd)
        os.remove(img)
        steps.ok(3, f"{rel['tag']} written")

        # 5. data back
        steps.run(4, "relieved")
        plat.settle(disk["name"])
        write_at(raw, start * SECTOR, data)
        if read_at(raw, start * SECTOR, count * SECTOR) != data:
            raise Failed((4, f"/data differs from the backup; it is safe in {backup}/data.img"))
        steps.ok(4, "XP, friends and keys checked byte for byte")

        # 6. settings back
        steps.run(5, "relieved")
        if toml is None:
            steps.ok(5, "there were none, the gotchi starts with the defaults")
        else:
            mnt = plat.mount_boot(disk["name"])
            try:
                with open(os.path.join(mnt, "tokibot.toml"), "wb") as f:
                    f.write(toml)
                    f.flush()
                    os.fsync(f.fileno())
                with open(os.path.join(mnt, "tokibot.toml"), "rb") as f:
                    if f.read() != toml:
                        raise Failed((5, "tokibot.toml was not copied back"))
            finally:
                plat.umount_boot(mnt, disk["name"])
            steps.ok(5, "tokibot.toml with your Wi-Fi and token")
        plat.eject(disk["name"])
        screen.mood = "done"
        return True
    except Failed as e:
        i, msg = e.args[0]
        steps.fail(i, msg)
        return False
    except Exception as e:  # noqa: BLE001 — show it instead of a traceback
        i = next((i for i, s in enumerate(steps.state) if s == "run"), 0)
        steps.fail(i, f"{type(e).__name__}: {e}")
        return False
    finally:
        steps.close()


def read_boot(plat, disk):
    """Board and settings from the card's FAT partition."""
    mnt = plat.mount_boot(disk["name"])
    try:
        with open(os.path.join(mnt, "config.txt")) as f:
            config = f.read()
        model = "zero2w" if re.search(r"^arm_64bit=1", config, re.M) else "zerow"
        toml = None
        for name in ("tokibot.toml", "claudegotchi.toml"):
            p = os.path.join(mnt, name)
            if os.path.exists(p):
                with open(p, "rb") as f:
                    toml = f.read()
                break
    finally:
        plat.umount_boot(mnt, disk["name"])
    ssid = ""
    if toml:
        m = re.search(rb'^\s*ssid\s*=\s*"([^"]*)"', toml, re.M)
        ssid = m.group(1).decode("utf-8", "replace") if m else ""
    return model, toml, ssid


def main():
    ap = argparse.ArgumentParser(description="Put a new Tokibot image on an SD card, keeping its progress.")
    ap.add_argument("--disk", help="the card (macOS: disk4, Linux: sdb or mmcblk0); asked when left out")
    args = ap.parse_args()

    if sys.platform not in ("darwin", "linux"):
        sys.exit("Only macOS and Linux are supported. On Windows, flash with Raspberry Pi Imager.")
    if os.geteuid() != 0:
        print("Writing an SD card needs administrator rights, so sudo asks for your password.")
        keep = [f"{k}={v}" for k, v in os.environ.items() if k.startswith("TOKIBOT_")]
        os.execvp("sudo", ["sudo", "env", *keep, sys.executable, os.path.abspath(__file__)] + sys.argv[1:])
    plat = Mac() if sys.platform == "darwin" else Linux()
    try:
        tty = open("/dev/tty", "r+", encoding="utf-8")
    except OSError:
        sys.exit("No terminal to talk to; run it in a terminal window.")

    import termios
    import tty as ttymod
    old = termios.tcgetattr(tty.fileno())
    screen = Screen(tty)

    def restore(*_):
        termios.tcsetattr(tty.fileno(), termios.TCSADRAIN, old)
        screen.write("\033[?25h\n")

    signal.signal(signal.SIGTERM, lambda *_: (restore(), sys.exit(1)))
    ttymod.setcbreak(tty.fileno())
    screen.write("\033[?25l\033[2J")
    code = 1
    try:
        code = session(screen, plat, args)
    except KeyboardInterrupt:
        screen.help = "stopped"
        screen.draw()
    finally:
        restore()
    sys.exit(code)


def wait_key(screen, text, mood):
    screen.mood, screen.help = mood, text
    screen.draw()
    return read_key(screen.tty)


def session(screen, plat, args):
    screen.facts = [("Card", "looking …")]
    screen.body = [f"  {screen.spin()} Looking for your gotchi's SD card …"]
    screen.help = ""
    screen.draw()

    # The card
    while True:
        disks = [d for d in plat.disks() if 0 < d["size"] <= MAX_BYTES]
        if args.disk:
            disks = [d for d in disks if d["name"] == args.disk.replace("/dev/", "").lstrip("r")]
        if disks:
            break
        screen.body = ["  No SD card found. Insert the gotchi's card (a card reader is fine)."]
        if wait_key(screen, "enter to look again · esc to quit", "waiting") == "esc":
            return 1
    disks.sort(key=lambda d: not is_tokibot(d))
    if len(disks) == 1 and is_tokibot(disks[0]):
        disk = disks[0]
    else:
        opts = [(f"{d['name']}  {human(d['size'])}",
                 ("Tokibot card" if is_tokibot(d) else d["model"] or "not a Tokibot card")) for d in disks]
        i = menu(screen, "Which card is the gotchi's?", opts)
        if i is None:
            return 1
        disk = disks[i]
    plat.unmount(disk["name"])
    try:
        model, toml, ssid = read_boot(plat, disk)
    except Exception:
        screen.body = [f"  {RED}{disk['name']} has no Tokibot boot partition.{RESET}",
                       "  For a new card, use Raspberry Pi Imager and the download page."]
        wait_key(screen, "any key to quit", "error")
        return 1
    disk["toml"] = toml
    screen.facts = [("Card", f"{disk['name']} · {human(disk['size'])}"),
                    ("Board", BOARDS[model]),
                    ("Wi-Fi", ssid or f"{DIM}none{RESET}"),
                    ("Settings", "tokibot.toml" if toml else f"{DIM}none{RESET}")]

    # The version
    screen.body = [f"  {screen.spin()} Looking up the versions …"]
    screen.draw()
    try:
        rels = releases(model)
    except Exception as e:
        screen.body = [f"  {RED}No versions found: {e}{RESET}", "  Are you online?"]
        wait_key(screen, "any key to quit", "error")
        return 1
    opts = [(r["tag"], f"{r['date']}{'  · newest' if r['latest'] else ''}") for r in rels]
    i = menu(screen, "Which version should the card get?", opts)
    if i is None:
        return 1
    rel = rels[i]
    screen.facts.append(("Version", f"{ACCENT}{rel['tag']}{RESET}"))

    # Confirm
    home = os.path.expanduser(f"~{os.environ.get('SUDO_USER', '')}")
    backup = os.path.join(home, f"tokibot-backup-{time.strftime('%Y-%m-%d-%H%M%S')}")
    screen.facts.append(("Backup", "~/" + os.path.basename(backup)))
    i = menu(screen, f"Erase {disk['name']} and put {rel['tag']} on it? Your progress is kept.",
             [("Yes, update the card", "backs up first"), ("No, stop", "")], mood="permission")
    if i != 0:
        return 1

    ok = update(screen, plat, disk, rel, backup)
    uid, gid = os.environ.get("SUDO_UID"), os.environ.get("SUDO_GID")
    if uid and os.path.isdir(backup):
        for root, dirs, files in os.walk(backup):
            for n in [root] + [os.path.join(root, f) for f in files]:
                try:
                    os.chown(n, int(uid), int(gid or uid))
                except OSError:
                    pass
    if ok:
        screen.body.append("")
        screen.body.append(f"  {GREEN}Done.{RESET} Put the card into the gotchi and switch it on.")
        wait_key(screen, "any key to quit", "done")
        return 0
    screen.body.append("")
    screen.body.append(f"  Nothing is lost: the backup is in {backup}.")
    wait_key(screen, "any key to quit", "error")
    return 1


if __name__ == "__main__":
    main()
