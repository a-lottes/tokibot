"""Draws the critter's moods as braille text for the card updater (docs/update-card.py).

The updater runs on its own on the user's computer, without the app, so the art is
pasted into it between two marker lines. Run `make tui-critters` after changing the
critter; the tests check that the pasted art is current.
"""
import os
import sys

from PIL import Image, ImageDraw

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from tokibot import critter  # noqa: E402

MOODS = ("ready", "waiting", "permission", "working", "hungry", "flow", "relieved", "done", "error")
CROP = (8, 8, 96, 80)          # the critter with room for its props, in px
BEGIN = "# --- critters: generated by app/tools/tui_critters.py, do not edit ---"
END = "# --- end of critters ---"
# Braille dot bits for (x, y) in a 2 × 4 cell
DOTS = {(0, 0): 0x01, (0, 1): 0x02, (0, 2): 0x04, (1, 0): 0x08,
        (1, 1): 0x10, (1, 2): 0x20, (0, 3): 0x40, (1, 3): 0x80}


def braille(img):
    w, h = img.size
    px = img.load()
    rows = []
    for y in range(0, h, 4):
        row = ""
        for x in range(0, w, 2):
            bits = 0
            for (dx, dy), bit in DOTS.items():
                if x + dx < w and y + dy < h and px[x + dx, y + dy] == 0:
                    bits |= bit
            row += chr(0x2800 + bits)
        rows.append(row)
    return rows


def art(mood, frame):
    img = Image.new("1", (110, 90), 255)
    critter.draw(ImageDraw.Draw(img), 10, 26, mood, frame)
    img = img.crop(CROP)
    return braille(img.resize((img.width // 2, img.height // 2), Image.NEAREST))


def block():
    lines = [BEGIN, "CRITTERS = {"]
    for mood in MOODS:
        lines.append(f"    {mood!r}: [")
        for frame in range(critter.frames(mood)):
            lines.append("        [" + ", ".join(repr(r) for r in art(mood, frame)) + "],")
        lines.append("    ],")
    lines += ["}", END]
    return "\n".join(lines)


def paste(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    new = text[:start] + block() + text[end:]
    if new != text:
        with open(path, "w", encoding="utf-8") as f:
            f.write(new)
    return new != text


if __name__ == "__main__":
    target = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(__file__), "..", "..", "docs", "update-card.py")
    print("updated" if paste(target) else "already current", target)
