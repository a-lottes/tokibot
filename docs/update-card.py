class Linux:
    def disks(self):
        data = json.loads(run("lsblk", "-J", "-b", "-o", "NAME,SIZE,RM,TRAN,TYPE,LABEL,MODEL"))
        found = []
        for d in data.get("blockdevices", []):
            if d.get("type") != "disk":
                continue
            removable = str(d.get("rm")) in ("1", "True", "true") or d.get("tran") == "usb" \
                or d["name"].startswith("mmcblk")
            if not removable:
                continue
            labels = [c.get("label") or "" for c in d.get("children", [])]
            found.append({"name": d["name"], "size": int(d.get("size") or 0), "labels": labels,
                          "model": (d.get("model") or "").strip()})
        return found

    def raw(self, disk):
        return f"/dev/{disk}"

    def boot_part(self, disk):
        return f"/dev/{disk}p1" if disk[-1].isdigit() else f"/dev/{disk}1"

    def unmount(self, disk):
        for line in run("lsblk", "-nro", "NAME,MOUNTPOINT", f"/dev/{disk}").splitlines():
            parts = line.split(maxsplit=1)
            if len(parts) == 2:
                run("umount", f"/dev/{parts[0]}", check=False)

    def settle(self, disk):
        run("blockdev", "--rereadpt", f"/dev/{disk}", check=False)
        time.sleep(2)
        self.unmount(disk)

    def mount_boot(self, disk):
        mnt = tempfile.mkdtemp(prefix="tokibot-boot-")
        run("mount", self.boot_part(disk), mnt)
        return mnt

    def umount_boot(self, mnt, disk):
        run("umount", mnt, check=False)
        os.rmdir(mnt)

    def eject(self, disk):
        run("sync", check=False)
        run("eject", f"/dev/{disk}", check=False)


