ACCENT, DIM, BOLD, GREEN, RED, RESET = ("\033[38;5;173m", "\033[2m", "\033[1m",
                                        "\033[32m", "\033[31m", "\033[0m")
SPINNER = "·✢✳∗✻✽✻∗✳✢"
WIDTH = 74


def visible(s):
    return len(re.sub(r"\033\[[0-9;]*m", "", s))


def pad(s, width):
    return s + " " * max(0, width - visible(s))


class Screen:
    """Redraws the whole UI in place: a box with the critter and facts, then a body."""

    def __init__(self, tty):
        self.tty = tty
        self.mood, self.facts, self.body, self.help = "ready", [], [], ""
        self.lock = threading.Lock()
        self.tick = 0

    def write(self, s):
        self.tty.write(s)
        self.tty.flush()

    def draw(self):
        with self.lock:
            frames = CRITTERS.get(self.mood) or CRITTERS.get("ready") or [[]]
            art = frames[(self.tick // 4) % len(frames)]
            inner = WIDTH - 2
            out = ["\033[H", ACCENT + "╭" + "─" * inner + "╮" + RESET]
            title = f" {ACCENT}✻{RESET} {BOLD}Tokibot card updater{RESET}"
            out.append(ACCENT + "│" + RESET + pad(title, inner) + ACCENT + "│" + RESET)
            rows = max(len(art), len(self.facts))
            for i in range(rows):
                left = art[i] if i < len(art) else " " * 22
                fact = self.facts[i] if i < len(self.facts) else ""
                if fact:
                    label, value = fact
                    fact = f"{DIM}{label:<9}{RESET}{value}"
                line = f" {ACCENT}{left}{RESET}  {fact}"
                out.append(ACCENT + "│" + RESET + pad(line, inner) + ACCENT + "│" + RESET)
            out.append(ACCENT + "╰" + "─" * inner + "╯" + RESET)
            out.append("")
            out += self.body
            out.append("")
            out.append(f"  {DIM}{self.help}{RESET}")
            self.write("\033[K\n".join(out) + "\033[K\033[J")

    def spin(self):
        return ACCENT + SPINNER[self.tick % len(SPINNER)] + RESET


def read_key(tty):
    ch = os.read(tty.fileno(), 1)
    if ch == b"\x1b":
        seq = os.read(tty.fileno(), 2)
        return {b"[A": "up", b"[B": "down"}.get(seq, "esc")
    if ch in (b"\r", b"\n"):
        return "enter"
    if ch in (b"k",):
        return "up"
    if ch in (b"j",):
        return "down"
    if ch in (b"q", b"\x03"):
        return "esc"
    return ""


def menu(screen, question, options, mood="waiting"):
    """options: [(label, detail)]. Returns the chosen index or None (esc)."""
    sel = 0
    screen.mood, screen.help = mood, "↑/↓ to select · enter to confirm · esc to cancel"
    while True:
        body = [f"  {BOLD}{question}{RESET}", ""]
        for i, (label, detail) in enumerate(options):
            mark = f"{ACCENT}❯{RESET}" if i == sel else " "
            text = f"{ACCENT}{label}{RESET}" if i == sel else label
            body.append(f"  {mark} {i + 1}. {text}" + (f"  {DIM}{detail}{RESET}" if detail else ""))
        screen.body = body
        screen.draw()
        key = read_key(screen.tty)
        if key == "up":
            sel = (sel - 1) % len(options)
        elif key == "down":
            sel = (sel + 1) % len(options)
        elif key == "enter":
            return sel
        elif key == "esc":
            return None


class Steps:
    """The list of steps below the box, Claude Code style: ⏺ title, ⎿ detail."""

    def __init__(self, screen, titles):
        self.screen, self.titles = screen, titles
        self.state = ["todo"] * len(titles)
        self.detail = [""] * len(titles)
        self.stop = threading.Event()
        self.thread = threading.Thread(target=self._animate, daemon=True)
        self.thread.start()

    def _animate(self):
        while not self.stop.wait(0.12):
            self.screen.tick += 1
            self.render()

    def render(self):
        body = []
        for i, title in enumerate(self.titles):
            st = self.state[i]
            dot = {"todo": f"{DIM}○{RESET}", "run": self.screen.spin(),
                   "ok": f"{GREEN}⏺{RESET}", "fail": f"{RED}⏺{RESET}"}[st]
            text = title if st != "todo" else f"{DIM}{title}{RESET}"
            body.append(f"  {dot} {text}")
            if self.detail[i] and st != "todo":
                body.append(f"    {DIM}⎿  {self.detail[i]}{RESET}")
        self.screen.body = body
        self.screen.draw()

    def run(self, i, mood, detail=""):
        self.state[i], self.detail[i], self.screen.mood = "run", detail, mood

    def note(self, i, detail):
        self.detail[i] = detail

    def ok(self, i, detail=None):
        self.state[i] = "ok"
        if detail is not None:
            self.detail[i] = detail

    def fail(self, i, detail):
        self.state[i], self.detail[i], self.screen.mood = "fail", detail, "error"

    def close(self):
        self.stop.set()
        self.thread.join()
        self.render()


def bar(done, total, width=24):
    frac = 0 if not total else min(1, done / total)
    full = int(frac * width)
    return f"{'█' * full}{'░' * (width - full)} {frac * 100:3.0f}%"


def human(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1000 or unit == "GB":
            return f"{n:.0f} {unit}" if unit in ("B", "KB") else f"{n:.1f} {unit}"
        n /= 1000


